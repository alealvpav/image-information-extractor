_language = None


def language_from_code(code):
    """'es_ES.UTF-8', 'es-MX', 'Spanish_Spain' o 'en' -> código soportado, o None."""
    code = (code or "").strip().lower()
    if code.startswith("spanish"):
        return "es"
    if code.startswith("english"):
        return "en"
    code = code[:2]
    return code if code in SUPPORTED_LANGUAGES else None


def windows_language():
    try:
        import ctypes
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
    except (ImportError, AttributeError, OSError):
        return None
    return WINDOWS_LANGUAGES.get(lang_id & 0x3FF)


def detect_language():
    # Mismo orden de prioridad que gettext; LANGUAGE puede ser una lista ("es:en")
    for variable in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        for value in os.environ.get(variable, "").split(":"):
            language = language_from_code(value)
            if language:
                return language
    if os.name == "nt":
        return windows_language() or DEFAULT_LANGUAGE
    return DEFAULT_LANGUAGE


def set_language(language):
    global _language
    _language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def get_language():
    if _language is None:
        set_language(detect_language())
    return _language


def _(key, **values):
    return MESSAGES[key][get_language()].format(**values)
